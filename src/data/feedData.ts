// Template for generating new feed entries
export function generateFeedEntry(
  actionType: ActionType,
  unitId: string,
  customerName: string,
  doorModel: string,
  outcome: StatusType,
  outcomeLabel: string,
  confidence: number,
  summary: string,
  triggerContext: {
    sensorReading: string;
    weatherCondition: string;
    sealAge: string;
    riskScore: number;
    riskLevel: 'Low' | 'Medium' | 'High' | 'Critical';
    decision: string;
  },
  revenue?: number
): FeedEntry {
  const firstName = customerName.split(' ')[0];

  const starterMessages: Record<string, { sender: 'agent' | 'customer'; content: string; timestamp: string }[]> = {
    'Proactive Outreach': [
      { sender: 'agent', content: `Hi ${firstName}, this is Schuco Service. Our monitoring detected elevated moisture on your sliding door. With rain forecasted, we recommend a preventive inspection. Are you available Wednesday or Thursday?`, timestamp: 'Just now' },
    ],
    'Sensor Alert': [
      { sender: 'agent', content: `[SYSTEM] Moisture sensor on unit ${unitId} triggered threshold alert. Automated risk assessment initiated. No customer contact yet.`, timestamp: 'Just now' },
    ],
    'Risk Assessment': [
      { sender: 'agent', content: `[SYSTEM] Automated risk assessment completed for unit ${unitId}. Score: ${triggerContext.riskScore}. Decision: ${triggerContext.decision}`, timestamp: 'Just now' },
    ],
    'Follow-up': [
      { sender: 'agent', content: `Hello ${firstName}! Following up on the service we completed recently. How is everything performing? Any questions?`, timestamp: 'Just now' },
    ],
    'Reminder Sent': [
      { sender: 'agent', content: `Reminder: Your Schuco maintenance appointment is coming up for unit ${unitId}. Please ensure clear access to the door track. Reply OK to confirm.`, timestamp: 'Just now' },
    ],
  };

  const conversation = (starterMessages[actionType] || []).map((msg, i) => ({
    ...msg,
    id: `msg-${Date.now()}-${i}`,
  }));

  return {
    id: `feed-${Date.now()}`,
    agentName: ['Agent Aria', 'Agent Nova', 'Agent Echo'][Math.floor(Math.random() * 3)],
    actionType,
    timestamp: new Date(),
    customerName,
    unitId,
    doorModel,
    summary,
    outcome,
    outcomeLabel,
    confidence,
    revenue,
    triggerContext,
    conversation,
    isNew: true,
  };
}

